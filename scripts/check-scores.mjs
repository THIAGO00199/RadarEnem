import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import vm from "node:vm";
import ts from "typescript";

const context = vm.createContext({ exports: {}, URL });
vm.runInContext(ts.transpileModule(await readFile("lib/scores.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, context);
const { numberValue, scoreValue, values, weightedAverage, newTarget, targetError, sanitizeScores, safeSource } = context.exports;
const scores = { linguagens: "600", humanas: "650", natureza: "700", matematica: "750", redacao: "900" };
assert.equal(weightedAverage(scores), 720);
assert.equal(weightedAverage(scores, { ...values("1"), matematica: "3", redacao: "2" }), 750);
assert.equal(weightedAverage({ ...scores, matematica: "650,5" }, values("1")), 700.1);
assert.equal(numberValue("0"), 0);
assert.equal(weightedAverage(values("0")), 0);
for (const raw of ["", " ", "-1", "NaN", "Infinity", "1e3", "600abc", "1.000,5"]) assert.equal(numberValue(raw), null, raw);
assert.equal(scoreValue("1008,3", "matematica"), 1008.3, "Objective TRI scores may exceed 1,000");
assert.equal(scoreValue("1001", "redacao"), null);
assert.equal(weightedAverage({ ...scores, humanas: "" }), null, "Missing is not zero");
assert.equal(weightedAverage(scores, values("0")), null, "No division by zero");
assert.equal(weightedAverage(scores, { ...values("1"), humanas: "-1" }), null);
assert.equal(weightedAverage(scores, { ...values("0"), redacao: "1" }), 900);
const target = { ...newTarget(), id: "target-1", course: "Engenharia", institution: "Universidade", year: "2025", cutoff: "740,5", source: "https://sisu.mec.gov.br/cursos" };
assert.equal(targetError(target), "");
assert.notEqual(targetError({ ...target, year: "" }), "");
assert.notEqual(targetError({ ...target, weights: values("0") }), "");
assert.notEqual(targetError({ ...target, source: "javascript:alert(1)" }), "");
assert.equal(safeSource("data:text/html,x"), "");
assert.equal(safeSource("https://user:secret@example.com"), "");
const original = { version: 1, kind: "boletim", scores, targets: [target] };
assert.equal(JSON.stringify(sanitizeScores(JSON.parse(JSON.stringify(original)))), JSON.stringify(original), "Saved score session round trip");
const malformed = sanitizeScores({ version: 1, scores: { matematica: "650,5", redacao: "1001" }, targets: [null, target, target, { ...target, id: "bad", weights: values("0") }, { ...target, id: "<script>" }] });
assert.equal(malformed.targets.length, 1);
assert.equal(malformed.scores.matematica, "650,5");
assert.equal(malformed.scores.redacao, "");
assert.equal(sanitizeScores({ ...original, version: 2 }).targets.length, 0);
assert.equal(sanitizeScores({ ...original, targets: Array.from({ length: 30 }, (_, i) => ({ ...target, id: `target-${i}` })) }).targets.length, 12);
console.log("Scores: independent weighted examples, decimals, missing/zero scores, TRI above 1,000, essay limit, invalid weights, reference context, unsafe URLs and persistence passed.");
