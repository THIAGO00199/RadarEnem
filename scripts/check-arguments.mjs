import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import vm from "node:vm";
const context = vm.createContext({});
for (const file of ["guia-mapas-01.js", "guia-mapas-02.js", "guia-mapas-03.js", "shared/argument-library-model.js"]) vm.runInContext(await readFile("portable/public/" + file, "utf8"), context);
const model = context.AtenaArguments, state = model.sanitize(null);
assert.equal(model.all().length, 18);
assert.equal(model.search({ ...state, query: "krenak natureza" }).length > 0, true);
assert.equal(model.search({ ...state, query: "zzz inexistente" }).length, 0);
const map = model.get("deepfakes");
const draft = { tese: "Meu texto autoral", argumento1: "Meu primeiro argumento" };
const filled = model.fillEmpty(draft, model.outline(map));
assert.equal(filled.value.tese, draft.tese); assert.equal(filled.value.argumento1, draft.argumento1); assert.equal(filled.added, 5);
const session = model.sanitize({ version: 1, active: map.id, tab: "roteiro", favorites: [map.id, map.id, "invalid"], drafts: { [map.id]: filled.value, invalid: draft } });
assert.equal(session.favorites.length, 1); assert.equal(Object.keys(session.drafts).length, 1);
assert.equal(JSON.stringify(model.sanitize(JSON.parse(JSON.stringify(session)))), JSON.stringify(session));
assert.equal(model.search({ ...session, onlyFavorites: true }).length, 1);
assert.equal(model.search({ ...session, onlyFavorites: true, favorites: [] }).length, 0);
assert.match(model.markdown(map, draft), /Meu texto autoral/); assert.match(model.markdown(map, draft), /https:\/\//);
assert.equal(model.sanitize({ version: 99, drafts: { [map.id]: draft } }).drafts[map.id], undefined);
assert.equal(model.fillEmpty({}, { tese: "x".repeat(2001) }).added, 0);
console.log("Arguments: search by all terms, empty states, per-map drafts, non-overwriting suggestions, favorites, backup-compatible round trip and sourced export passed.");
