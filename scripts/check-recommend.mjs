import {readFile} from "node:fs/promises";
import vm from "node:vm";
import assert from "node:assert/strict";
const context={module:{exports:{}},Intl,Date,globalThis:{}};
vm.runInNewContext(await readFile(new URL("../portable/public/shared/recommend.js",import.meta.url),"utf8"),context);
const {choose}=context.module.exports,now=new Date("2026-10-01T12:00:00Z");
const base={profile:{},area:{ling:0,hum:0,nat:0,mat:0,red:0},errors:[],flash:{},essays:[],draft:"",officialHistory:[],course:{done:{}}};
const state=(extra={})=>({...structuredClone(base),...extra});
assert.equal(choose(state(),now).area,"ling");
assert.equal(choose(state({profile:{d_mat:3}}),now).area,"mat");
assert.equal(choose(state({errors:[{reviewed:false}],draft:"a".repeat(80),flash:{f:{stage:1,due:"2026-09-30"}}}),now).key,"errors");
assert.equal(choose(state({errors:[{reviewed:true}]}),now).key,"start");
assert.equal(choose(state({flash:{f:{stage:0,due:"2026-10-01",last:"2026-10-01"}}}),now).key,"flash");
assert.equal(choose(state({flash:{f:{stage:1,due:"2026-10-01"}}}),new Date("2026-10-01T02:00:00Z")).key,"start");
assert.equal(choose(state({flash:{f:{stage:1,due:"2026-09-30"}}}),new Date("2026-10-01T02:00:00Z")).key,"flash");
assert.equal(choose(state({flash:{f:null}}),now).key,"start");
const draft="Uma redação em construção com um argumento que ainda precisa ser desenvolvido.";
assert.equal(choose(state({draft}),now).key,"draft");
assert.equal(choose(state({draft,essays:[{text:draft}]}),now).key,"start");
const exams=[{id:"e1",day:1},{id:"e2",day:2}];
assert.equal(choose(state({officialHistory:[{examId:"e2",first:12,second:34}]}),now,exams).area,"nat");
assert.equal(choose(state({officialHistory:[{examId:"e1",first:36,second:17}]}),now,exams).area,"hum");
assert.equal(choose(state({officialHistory:[{examId:"unknown",first:1,second:1}]}),now,exams).key,"start");
const original=state({course:{done:{mat1:true}}}),serialized=JSON.stringify(original);
assert.equal(choose(original,now).key,"continue");assert.equal(JSON.stringify(original),serialized);
console.log("Recommendations: 15 priority, timezone, saved draft, official score and immutability checks passed.");
